/** 把语言偏好解析为具体语言：auto → 跟随浏览器（zh* → zh，否则 en）。 */
export function resolveLang(pref: LangPref): Lang {
  if (pref === 'auto') {
    const nav = typeof navigator !== 'undefined' ? navigator.language : 'en';
    return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }
  return pref;
}
